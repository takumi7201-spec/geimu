/** 表示モードごとのカラーランプ */

import { clamp } from '../core/rng.js';

function ramp(stops) {
  return (t) => {
    t = clamp(t, 0, 1);
    for (let i = 0; i < stops.length - 1; i++) {
      const [p0, c0] = stops[i];
      const [p1, c1] = stops[i + 1];
      if (t <= p1) {
        const k = (t - p0) / Math.max(1e-6, p1 - p0);
        return [
          c0[0] + (c1[0] - c0[0]) * k,
          c0[1] + (c1[1] - c0[1]) * k,
          c0[2] + (c1[2] - c0[2]) * k,
        ];
      }
    }
    return stops[stops.length - 1][1];
  };
}

