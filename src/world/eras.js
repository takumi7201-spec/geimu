/**
 * 中生代の三つの紀の古地理定義。
 *
 * 座標系は正距円筒図法。x:0..1 が経度 360 度（左右はラップ）、
 * y:0..1 が北極から南極。緯度 = 90 - 180*y。
 *
 * 図法が 2:1 なので、rx（x 正規化）と ry（y 正規化）は ry = 2·rx のとき
 * 画面上で正円になる。大陸は「円に近い核をいくつも重ねて」形づくる。
 *
 * craton  : 大陸核。楕円状の正の影響場
 * sea     : 負の影響場。海路・内海・リフトを彫り込む
 * belt    : 造山帯。折れ線に沿って尾根ノイズを乗せる
 * volcano : 巨大火成岩石区・ホットスポット
 * oceans  : ラベルを置くための海域アンカー
 */

